#!/usr/bin/env python
"""Internal-geometry videos: what CRePE's radial head predicts while generating a showcase clip.

    python tools/geometry_videos.py <capture dir> [layer]

<capture dir>/<scene>/seed<k>.{mp4,npz} come from regenerating a showcase clip with a read-only hook on the radial
head (the research code's ``save_predicted_depth``: conditional pass of the last denoising step; npz holds ``mu`` and
``sigma`` of shape (layers, 21, 30, 52) for the CRePE blocks listed in ``layers``). The regenerated video must be
identical to the page's ``_source_videos/<scene>/crepe_seed<k>.mp4``.

Rendering follows the paper's layer-depth figures: inverse ray distance ``exp(-mu)`` (mu clamped to [-10, 3]) with the
turbo colormap (red = near), clipped to the 2nd-98th percentile of the clip, bilinearly upsampled from the 52 x 30
token grid. Latent frame j covers video frames 4j-3..4j (frame 0: latent 0), as in Wan's causal VAE.

Writes static/videos/geometry/<scene>/crepe_seed<k>.mp4 (+ poster), _source_videos/geometry/<scene>_seed<k>.npz
(git-ignored copy of the capture) and static/js/geometry-data.js for the examples in tools/geometry_examples.json.
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

import imageio_ffmpeg
import numpy as np
import torch
import torch.nn.functional as F
from matplotlib import colormaps

FF = imageio_ffmpeg.get_ffmpeg_exe()
root = Path(__file__).resolve().parents[1]
cap = Path(sys.argv[1])
LAYER = int(sys.argv[2]) if len(sys.argv) > 2 else 15
T, H, W = 81, 480, 832


def render(mu):
    inv = np.exp(-np.clip(mu, -10.0, 3.0)).astype(np.float32)                 # (21, 30, 52)
    lo, hi = np.percentile(inv, [2, 98])
    norm = np.clip((inv - lo) / max(hi - lo, 1e-9), 0, 1)
    up = F.interpolate(torch.from_numpy(norm)[:, None], size=(H, W), mode="bilinear", align_corners=False)[:, 0].numpy()
    idx = [0] + [(f + 3) // 4 for f in range(1, T)]                              # video frame -> latent frame
    rgb = (colormaps["turbo"](np.clip(up, 0, 1))[..., :3] * 255).astype(np.uint8)
    return rgb[idx]


def encode(frames, dst, poster):
    dst.parent.mkdir(parents=True, exist_ok=True)
    poster.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([FF, "-hide_banner", "-loglevel", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}",
                    "-framerate", "16", "-i", "pipe:", "-c:v", "libx264", "-preset", "slow", "-crf", "24",
                    "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an", str(dst)],
                   input=np.ascontiguousarray(frames).tobytes(), check=True)
    subprocess.run([FF, "-hide_banner", "-loglevel", "error", "-y", "-i", str(dst), "-vf", "select=eq(n\\,0)",
                    "-frames:v", "1", "-q:v", "4", str(poster)], check=True)


examples = json.load(open(root / "tools" / "geometry_examples.json"))
for ex in examples:
    scene, seed = ex["scene"], ex["seed"]
    video, npz = cap / scene / f"seed{seed}.mp4", cap / scene / f"seed{seed}.npz"
    page = root / "_source_videos" / scene / f"crepe_seed{seed}.mp4"
    assert video.read_bytes() == page.read_bytes(), f"regenerated video differs from the page video: {video}"
    data = np.load(npz)
    layers = list(data["layers"])
    mu = data["mu"][layers.index(LAYER)]
    dst = root / "static" / "videos" / "geometry" / scene / f"crepe_seed{seed}.mp4"
    encode(render(mu), dst, root / "static" / "posters" / "geometry" / scene / f"crepe_seed{seed}.jpg")
    keep = root / "_source_videos" / "geometry" / f"{scene}_seed{seed}.npz"
    keep.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(npz, keep)
    print(dst.relative_to(root), dst.stat().st_size // 1024, "KB", flush=True)

js = "// Generated by tools/geometry_videos.py. Do not edit by hand.\nwindow.CREPE_GEOMETRY = " + \
     json.dumps({"layer": LAYER, "examples": examples}, separators=(",", ":")) + ";\n"
(root / "static" / "js" / "geometry-data.js").write_text(js)
