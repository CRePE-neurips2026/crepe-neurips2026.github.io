#!/usr/bin/env python
"""Generate static/js/showcase-data.js from tools/lens_showcase.json and tools/picks.txt (default seed per card)."""
import json
import math
from pathlib import Path

import numpy as np

root = Path(__file__).resolve().parents[1]
TITLES = {
    "01_fox_fisheye": "Red fox in an autumn forest",
    "03_neon_city_drive": "Neon city drive", "04_ski_pov": "Ski run", "05_sea_turtle_reef": "Sea turtle reef",
    "06_aurora_lake": "Aurora over a frozen lake", "07_corgi_cherry": "Corgi under cherry blossoms",
    "08_coastal_city_sunset": "Coastal city at sunset",
    "10_lantern_festival": "Lantern festival",
    "12_airplane_night_city": "Night flight over a city", "13_waterfall_canyon": "Waterfall canyon",
}
picks = {}
for line in (root / "tools" / "picks.txt").read_text().split():
    scene, rest = line.split("__")
    model, seed = rest.split("_seed")
    picks.setdefault(scene, []).append({"model": model, "seed": int(seed)})


def lens(item, key):
    sched = item.get(f"{key}_schedule")
    if sched:
        return [float(sched["start"]), float(sched["end"])]
    return [float(item[key])]


VIEW_AZ, VIEW_EL = math.radians(-40.0), math.radians(28.0)
BOX_W, BOX_H = 150.0, 90.0   # SVG units of the trajectory panel (with margin)


def project(points):
    """World (OpenCV, -y up) -> oblique 2D view: x right, y up."""
    X, Y, Z = points[..., 0], points[..., 2], -points[..., 1]       # right, depth, up
    xr = X * math.cos(VIEW_AZ) - Y * math.sin(VIEW_AZ)
    yr = X * math.sin(VIEW_AZ) + Y * math.cos(VIEW_AZ)
    return np.stack([xr, Z * math.cos(VIEW_EL) + yr * math.sin(VIEW_EL)], axis=-1)


def trajectory_panel(path, fov0):
    """Projected camera path and frustum glyphs, fitted into a BOX_W x BOX_H box (SVG y down)."""
    pose = np.load(path).astype(np.float64)                  # (T, 3, 4) camera-to-world
    centers, R = pose[:, :, 3], pose[:, :, :3]
    extent = max(np.ptp(centers, axis=0).max(), 1e-3)
    size = 0.09 * extent
    half = math.radians(min(fov0, 110.0) / 2)
    frusta_idx = list(range(0, len(pose), 16))
    if frusta_idx[-1] != len(pose) - 1:
        frusta_idx.append(len(pose) - 1)
    glyphs = []
    for i in range(len(pose)):
        right, down, fwd = R[i][:, 0], R[i][:, 1], R[i][:, 2]
        corners = [centers[i] + size * (fwd + sx * math.tan(half) * right + sy * math.tan(half) * 0.58 * down)
                   for sx, sy in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
        glyphs.append(np.stack([centers[i]] + corners))
    glyphs = project(np.stack(glyphs))                       # (T, 5, 2)
    pts = glyphs.reshape(-1, 2)
    lo, hi = pts.min(0), pts.max(0)
    scale = min(BOX_W / max(hi[0] - lo[0], 1e-6), BOX_H / max(hi[1] - lo[1], 1e-6))
    off = np.array([(160 - (hi[0] - lo[0]) * scale) / 2, (100 - (hi[1] - lo[1]) * scale) / 2])

    def to_svg(q):
        q = (q - lo) * scale + off
        return [round(float(q[..., 0]), 1), round(float(100 - q[..., 1]), 1)] if q.ndim == 1 else \
               [[round(float(a), 1), round(float(100 - b), 1)] for a, b in q]

    return {
        "path": [to_svg(g[0]) for g in glyphs],
        "frusta": [{"i": i, "pts": to_svg(glyphs[i])} for i in range(len(pose))],
        "key": frusta_idx,
    }


ref_file = root / "tools" / "references.json"           # tools/prepare_references.py
references = json.loads(ref_file.read_text()) if ref_file.exists() else {}


def reference(item):
    ref = references.get(Path(item["trajectory"]).stem)
    if not ref:
        return None
    assert (root / "static" / "videos" / "reference" / f"{ref['clip']}.mp4").exists(), ref
    return {"clip": ref["clip"], "fov": ref["fov"], "xi": ref["xi"]}


scenes = []
for item in json.load(open(root / "tools" / "lens_showcase.json")):
    name = item["name"]
    for model in ("crepe", "ucpe"):
        for seed in range(3):
            assert (root / "static" / "videos" / name / f"{model}_seed{seed}.mp4").exists(), (name, model, seed)
    scenes.append({
        "reference": reference(item),
        "id": name, "title": TITLES[name], "caption": item["caption"],
        "fov": lens(item, "x_fov"), "xi": lens(item, "xi"),
        "trajectory": "PanShot" if "panshot_" in item["trajectory"] else "RealEstate10K",
        "picks": picks.get(name, [{"model": "crepe", "seed": 0}]),
        "camera": trajectory_panel(root / "tools" / "trajectories" / Path(item["trajectory"]).name, lens(item, "x_fov")[0]),
    })
js = "// Generated by tools/build_data.py. Do not edit by hand.\nwindow.CREPE_SHOWCASE = " + json.dumps(scenes, separators=(",", ":"), ensure_ascii=False) + ";\n"
(root / "static" / "js" / "showcase-data.js").write_text(js)
print(f"{len(scenes)} scenes")
