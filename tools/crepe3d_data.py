#!/usr/bin/env python
"""Data for the interactive CRePE explainer (static/js/crepe3d.js).

    python tools/crepe3d_data.py <CRePE code repo>

Uses the CRePE fox-fisheye showcase video (``_source_videos/01_fox_fisheye/crepe_seed2.mp4``), its requested
trajectory and lens. Writes the key / query frames to ``static/images/crepe3d/`` and the camera poses, lens and the
default key token to ``static/js/crepe3d-data.js``. The default log-distance centre ``mu`` is the depth along the
key token's ray whose projection lands on the same point (the fox's head) in the last frame.
"""
import json
import sys
from pathlib import Path

import imageio.v3 as iio
import numpy as np

root = Path(__file__).resolve().parents[1]
repo = Path(sys.argv[1])
sys.path.insert(0, str(repo))
from crepe import load_trajectory  # noqa: E402

SCENE, SEED = "01_fox_fisheye", 2
W, H, TOKEN = 832, 480, 16
FRAMES = (0, 20, 40, 60, 80)
KEY_TOKEN = (15, 11)              # token column / row: the fox's head in frame 0
TARGET_LAST = (365.0, 155.0)      # the fox's head in frame 80 (pixels)

sample = {s["name"]: s for s in json.load(open(repo / "demo" / "lens_showcase.json"))}[SCENE]
fov, xi = float(sample["x_fov"]), float(sample["xi"])
traj = sample["trajectory"] if Path(sample["trajectory"]).is_absolute() else str(repo / sample["trajectory"])
poses = np.asarray(load_trajectory(traj, num_frames=81), dtype=np.float64)          # (81, 3, 4) camera-to-world
fx = W / 2 * (np.cos(np.radians(fov / 2)) + xi) / np.sin(np.radians(fov / 2))


def unproject(u, v):
    x, y = (u - W / 2) / fx, (v - H / 2) / fx
    r2 = x * x + y * y
    g = (xi + np.sqrt(1 + (1 - xi * xi) * r2)) / (1 + r2)
    d = np.array([g * x, g * y, g - xi])
    return d / np.linalg.norm(d)


def project(p):
    a = p[2] + xi * np.linalg.norm(p)
    return np.array([fx * p[0] / a + W / 2, fx * p[1] / a + H / 2])


ray = unproject((KEY_TOKEN[0] + 0.5) * TOKEN, (KEY_TOKEN[1] + 0.5) * TOKEN)
c2w = np.eye(4)
c2w[:3] = poses[80]
w2c = np.linalg.inv(c2w)
grid = np.linspace(-3, 3, 6001)
err = [np.linalg.norm(project((w2c @ np.append(np.exp(g) * ray, 1))[:3]) - TARGET_LAST) for g in grid]
mu = float(grid[int(np.argmin(err))])
print(f"default mu {mu:.3f} (reprojection error {min(err):.1f} px)")

out = root / "static" / "images" / "crepe3d"
out.mkdir(parents=True, exist_ok=True)
video = iio.imread(root / "_source_videos" / SCENE / f"crepe_seed{SEED}.mp4")
for i in FRAMES:
    iio.imwrite(out / f"frame_{i:02d}.jpg", video[i], quality=85)

data = {
    "width": W, "height": H, "token": TOKEN, "x_fov": fov, "xi": xi,
    "frames": {str(i): f"static/images/crepe3d/frame_{i:02d}.jpg" for i in FRAMES},
    "poses": [np.round(p, 5).reshape(-1).tolist() for p in poses],
    "key_token": list(KEY_TOKEN), "mu": round(mu, 3), "sigma": 1.0,
}
js = "// Generated by tools/crepe3d_data.py. Do not edit by hand.\nwindow.CREPE_3D = " + \
     json.dumps(data, separators=(",", ":")) + ";\n"
(root / "static" / "js" / "crepe3d-data.js").write_text(js)
