#!/usr/bin/env python
"""Zero-shot RealCam-Vid examples for the camera-control comparison.

    python tools/prepare_realcam.py <RealCam-Vid_test.npz> <crepe dir> <ucpe dir> <crepe pose glob> <ucpe pose glob>

The videos were generated by the code repository's release pipeline from the RealCam-Vid test metadata (camera +
caption only), following the paper's metric-camera protocol: world-to-camera extrinsics inverted, camera centres
multiplied by ``align_factor``, made relative to the first frame (first 81 poses); horizontal FoV from the normalised
focal length, xi = 0 (pinhole); prompt = ``long_caption``; 50 steps, CFG 5, seed 0. CRePE = projdepth-b16, UCPE =
ucpe-b16. Video files are ``<dir>/<idx:04d>_<video_id>.mp4``; ViPE poses ``<glob with {stem}>``.

For the examples in tools/realcam_examples.json this writes
* _source_videos/realcam/<idx>/{crepe,ucpe}.mp4 (git-ignored originals), static/videos/realcam/<idx>/{crepe,ucpe}.mp4
  (H.264, CRF 24) and static/posters/realcam/<idx>/{crepe,ucpe}.jpg;
* tools/vipe_poses/realcam_<idx>__{crepe,ucpe}.npz (ViPE camera-to-world poses of the generated videos);
* tools/realcam_cameras.json: requested trajectory, caption, lens and camera-motion statistics per example,
  so tools/vipe_tracks.py can rebuild static/js/camera-data.js without the dataset.
"""
import glob
import json
import math
import shutil
import subprocess
import sys
from pathlib import Path

import imageio_ffmpeg
import numpy as np

FF = imageio_ffmpeg.get_ffmpeg_exe()
root = Path(__file__).resolve().parents[1]
npz, dirs, pose_globs = sys.argv[1], {"crepe": sys.argv[2], "ucpe": sys.argv[3]}, {"crepe": sys.argv[4], "ucpe": sys.argv[5]}
data = np.load(npz, allow_pickle=True)["arr_0"]


def requested(e):
    c2w = np.linalg.inv(e["camera_extrinsics"][:81].astype(np.float64))
    c2w[:, :3, 3] *= float(e["align_factor"])
    return np.linalg.inv(c2w[0])[None] @ c2w                         # (81, 4, 4), metric, relative to frame 0


cameras = {}
for ex in json.load(open(root / "tools" / "realcam_examples.json")):
    i = ex["idx"]
    e = data[i]
    stem = f"{i:04d}_{Path(e['video_path']).stem}"
    for model in ("crepe", "ucpe"):
        src = Path(dirs[model]) / f"{stem}.mp4"
        orig = root / "_source_videos" / "realcam" / str(i) / f"{model}.mp4"
        web = root / "static" / "videos" / "realcam" / str(i) / f"{model}.mp4"
        poster = root / "static" / "posters" / "realcam" / str(i) / f"{model}.jpg"
        for p in (orig, web, poster):
            p.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, orig)
        subprocess.run([FF, "-hide_banner", "-loglevel", "error", "-y", "-i", str(orig), "-c:v", "libx264", "-preset",
                        "slow", "-crf", "24", "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an", str(web)], check=True)
        subprocess.run([FF, "-hide_banner", "-loglevel", "error", "-y", "-i", str(orig), "-vf", "select=eq(n\\,0)",
                        "-frames:v", "1", "-q:v", "4", str(poster)], check=True)
        hits = glob.glob(pose_globs[model].replace("{stem}", stem))
        assert len(hits) == 1, (model, stem, hits)
        shutil.copyfile(hits[0], root / "tools" / "vipe_poses" / f"realcam_{i}__{model}.npz")
    rel = requested(e)
    R = rel[:, :3, :3]
    turn = np.degrees(np.arccos(np.clip((np.trace(R, axis1=1, axis2=2) - 1) / 2, -1, 1))).max()
    travel = np.linalg.norm(np.diff(rel[:, :3, 3], axis=0), axis=1).sum()
    cameras[str(i)] = {
        "video_id": Path(e["video_path"]).stem, "source": e["dataset_source"], "title": ex["title"],
        "caption": e["long_caption"], "short_caption": e["short_caption"],
        "x_fov": round(2 * math.degrees(math.atan(0.5 / float(e["camera_intrinsics"][0]))), 1),
        "turn_deg": round(float(turn), 1), "travel_m": round(float(travel), 1),
        "pose": np.round(rel[:, :3, :4], 5).reshape(81, 12).tolist(),
    }
    print(i, ex["title"], cameras[str(i)]["turn_deg"], "deg", cameras[str(i)]["travel_m"], "m", flush=True)
(root / "tools" / "realcam_cameras.json").write_text(json.dumps(cameras, indent=1))
